export const LEXICON: ReadonlySet<string> = new Set(
  RAW.split(/\s+/)
    .map((word) => word.trim().toUpperCase())
    .filter((word) => /^[A-Z]{2,}$/.test(word)),
)

let imported: Set<string> | null = null

export function foldWord(word: string): string {
  return word
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toUpperCase()
    .replace(/[^A-Z]/g, '')
}

export function setImportedWords(words: Iterable<string> | null): number {
  if (!words) {
    imported = null
    return 0
  }
  const next = new Set<string>()
  for (const word of words) {
    const folded = foldWord(word)
    if (folded.length >= 2 && folded.length <= 15) next.add(folded)
  }
  imported = next.size > 0 ? next : null
  return imported?.size ?? 0
}

export function importedCount(): number {
  return imported?.size ?? 0
}

export function lexiconNote(): string {
  const count = importedCount()
  if (count === 0) return 'liste de départ'
  return `liste de départ + ${count.toLocaleString('fr-FR')} mots importés`
}

export function isWord(word: string): boolean {
  const folded = foldWord(word)
  if (folded.length < 2) return false
  return LEXICON.has(folded) || imported?.has(folded) === true
}
